import argparse
import sys

STORAGE_OPTIONS = [
    "sqlite",
    "redis",
    "mongo",
    "gridfs",
    "mongo-file",
    "mongo-gridfs",
    "file",
    "mysql",
]

STABLE_EXEC_MODES = ["no-cache", "manual"]
# Research in progress (decision D8): they need @maybe_deterministic, which setup
# injects only when it is run with the same --exec-mode.
EXPERIMENTAL_EXEC_MODES = ["accurate", "probabilistic-counting", "probabilistic-error"]
EXEC_MODES = STABLE_EXEC_MODES + EXPERIMENTAL_EXEC_MODES

EXPERIMENTAL_DESCRIPTION = (
    "Research in progress, not recommended: they may return results that differ "
    "from the uncached run. They apply only to the execution modes accurate, "
    "probabilistic-counting and probabilistic-error, and need setup run with the "
    "same --exec-mode. See docs/experimental.md."
)


def help_msg() -> str:
    return (
        tool_options_msg()
        + exec_mode_msg()
        + hashes_msg()
        + storage_msg()
        + serializer_msg()
        + memory_architecture_msg()
        + retrieval_strategies_msg()
        + retrieval_exec_modes_msg()
        + experimental_msg()
    )


def tool_options_msg():
    return (
        "\nSpeeduPy's command line arguments help:\n\n\
    To run your experiment with SpeeduPy use:\n\
    $ python "
        + str(sys.argv[0])
        + " program_arguments [-h, --help] [OPTIONS]\n\n\
    To run in the SpeeduPy DEBUG mode use:\n\
    $ DEBUG=True python "
        + str(sys.argv[0])
        + " program_arguments [-h, --help] [OPTIONS]\n\n"
    )


def exec_mode_msg():
    return "\nExecution Mode - Defines how SpeeduPy will execute:\n\
    =>no-cache               : SpeeduPy will cache no functions\n\
    =>manual                 : SpeeduPy only caches the functions annotated by the user with @deterministic (default)\n"


def experimental_msg():
    return "\nExperimental (beta). Research in progress, not recommended: results may differ from the uncached run. See docs/experimental.md.\n\
\nExperimental execution modes (--exec-mode):\n\
    =>accurate               : SpeeduPy looks for statistically pure functions and only caches function calls that always returned the same output\n\
    =>probabilistic-counting : SpeeduPy looks for statistically pure functions and caches function calls whose most produced output occurred at least a minimum percentage of times defined by the user. The output that appeared most times will always be returned.\n\
    =>probabilistic-error    : SpeeduPy looks for statistically pure functions and caches function calls that introduce errors up to a user-specified limit\n\
\nRevalidation options (--revalidation):\n\
    =>none       : SpeeduPy will never reexecute a function it classified as statistically pure\n\
    =>fixed      : SpeeduPy will reexecute a function it classified as statistically pure always after a fixed number of cached function calls\n\
    =>adaptative : SpeeduPy will reexecute a function it classified as statistically pure. The number of cached function calls before the revalidation occurs varies according to the historical behaviour of the function.\n"


def hashes_msg():
    return "\nHashes: \n\
    => xxhash   : Extremely fast non-cryptographic hash with very high performance and good collision resistance (default, recommended).\n\
    => md5      : Cryptographic hash function with strong collision resistance.\n\
    => a5hash   : Research-grade. High-performance non-cryptographic hash designed for speed and efficiency.\n\
    => museair  : Research-grade. High-performance non-cryptographic hash designed for excellent speed and distribution.\n\
Research-grade hashes: available and fully tested.\n"


def storage_msg():
    return "\nStorage:\n\
    =>sqlite       : use a SQLite database to store data\n\
    =>redis        : use a Redis database to store data\n\
    =>mongo        : use a Mongo database to store data\n\
    =>gridfs       : use a Mongo GridFS database to store data\n\
    =>mongo-file   : use a Mongo database to store data. If data does not fit in a mongo document it is stored in the filesystem.\n\
    =>mongo-gridfs : use a Mongo database to store data. If data does not fit in a mongo document it is stored in with Mongo GridFS.\n\
    =>mysql        : use a MySQL database to store data\n\
    =>file         : use the filesystem to store data.\n"


def serializer_msg():
    return "\nSerializer:\n\
    =>pickle      : use Pickle as serialization mechanism\n\
    =>cloudpickle : use Cloudpickle as serialization mechanism\n"


def memory_architecture_msg():
    return "\nMemory architecture options:\n\
    =>0-dict      : SpeeduPy will always request and save data directly on the storage.\n\
    =>1-dict      : SpeeduPy will save the data loaded from the storage and the new data generated by the experiment in the same dictionary. It will be good during the execution of the experiment, but there may be an overhead for SpeeduPy to save the new data into storage.\n\
    =>2-dict      : SpeeduPy will save the data loaded from the storage in one dictionary and the new data generated by the experiment in another dictionary. It will be good for saving new data into the storage, but there may be an overhead for SpeeduPy to search for data during the experiment execution\n\
    =>2-dict-fast : SpeeduPy will save the data loaded from the storage and the new data generated by the experiment in the same dictionary, but there will be a second dictionary with the references to the new data generated by the experiment. This setup should produce a good performance, but it will consume more RAM space.\n\
    =>memcached-wt: Uses Memcached with a write-through policy (writes to RAM and persistent storage at the same time).\n\
    =>memcached-wb: Uses Memcached with a write-back policy (writes to RAM immediately, saves to persistent storage later).\n"


def retrieval_strategies_msg():
    return "\nRetrieval strategy options:\n\
    =>lazy     : SpeeduPy will always request only the data required for the experiment execution.\n\
    =>function : SpeeduPy will request all the data of a function when the experiment needs a specific data of a function\n\
    =>eager    : SpeeduPy will request all data saved on the storage before the experiment starts to execute\n"


def retrieval_exec_modes_msg():
    return "\nRetrieval execution mode options:\n\
    =>sequential : SpeeduPy will always request data from the storage sequentially, blocking the experiment execution during this process.\n\
    =>thread     : SpeeduPy will request data from the storage using a thread. It will allow the experiment to execute while the data is being loaded to RAN\n"


def build_parser() -> argparse.ArgumentParser:
    """The parser of the execution options; test/test_readme.py reads it."""
    exec_modes = EXEC_MODES
    revalidations = ["none", "fixed", "adaptative"]
    retrieval_strategies = ["lazy", "function", "eager"]
    retrieval_exec_modes = ["sequential", "thread"]
    memory_architectures = [
        "0-dict",
        "1-dict",
        "2-dict",
        "2-dict-fast",
        "memcached-wt",
        "memcached-wb",
    ]
    hashes = ["xxhash", "md5", "a5hash", "museair"]
    storage_options = STORAGE_OPTIONS
    serializer_options = ["pickle", "cloudpickle"]

    speedupy_arg_parser = argparse.ArgumentParser(usage=help_msg())

    speedupy_arg_parser.add_argument(
        "args",
        metavar="program arguments",
        nargs="*",
        type=str,
        help="program arguments",
    )

    speedupy_arg_parser.add_argument(
        "--exec-mode",
        choices=exec_modes,
        metavar="",
        nargs=1,
        default=["manual"],
        help="defines how SpeeduPy will execute: "
        + ", ".join(STABLE_EXEC_MODES)
        + " (default: manual). The modes "
        + ", ".join(EXPERIMENTAL_EXEC_MODES)
        + " are experimental (beta), see docs/experimental.md",
    )

    experimental_group = speedupy_arg_parser.add_argument_group(
        "Experimental options (beta)", EXPERIMENTAL_DESCRIPTION
    )

    experimental_group.add_argument(
        "--revalidation",
        choices=revalidations,
        metavar="",
        default=["adaptative"],
        nargs=1,
        help="defines if Speedupy should reexecute a function sometimes to validate that the function continues to be safe to cache. There are three possible variations for this algorithm, depending on the execution mode selected.",
    )

    experimental_group.add_argument(
        "--max-num-exec-til-revalidation",
        default=10,
        metavar="",
        type=int,
        nargs=1,
        help="defines the maximum number of times a function can be cached before a revalidation occurs.",
    )

    experimental_group.add_argument(
        "--reduction-factor",
        default=0.3,
        metavar="",
        type=float,
        nargs=1,
        help="defines the factor used to update the next number of cached functions before the next revalidation occurs.",
    )

    experimental_group.add_argument(
        "--min-num-exec",
        default=20,
        metavar="",
        type=int,
        nargs=1,
        help="defines the minimum number of times SpeeduPy must execute a function call before trying to cache it",
    )

    experimental_group.add_argument(
        "--min-mode-occurrence",
        default=0.8,
        metavar="",
        nargs=1,
        help='used when "exec-mode=probabilistic-counting" is set. Defines the minimum frequency of appearances (in percentage) that the statistical mode must have for a function to be accelerated. The value informed must be between 0 and 1.',
    )

    experimental_group.add_argument(
        "--confidence-level",
        default=0.95,
        metavar="",
        nargs=1,
        help='used when "exec-mode=probabilistic-error" is set. Defines the confidence level used to estimate the margim of error and confidence interval of a function. The value informed must be between 0 and 1.',
    )

    experimental_group.add_argument(
        "--max-error-per-function",
        default=None,
        metavar="",
        nargs=1,
        help='used when "exec-mode=probabilistic-error" is set. Defines the maximum error the user considers acceptable for a function to introduce when it is cached. This error correspond to the margin of error of the confidence interval calculated. Notice, that an execution of a function can produce an output that is not inside the confidence interval, in which case the error produced by the function would be greater then the margin of error the confidence interval. The probability of this occurring is (1 - confidence_level).',
    )

    speedupy_arg_parser.add_argument(
        "--retrieval-strategy",
        choices=retrieval_strategies,
        metavar="",
        nargs=1,
        type=str,
        default=["eager"],
        help="Defines how SpeeduPy's should load cached data saved on the storage",
    )

    speedupy_arg_parser.add_argument(
        "--retrieval-exec-mode",
        choices=retrieval_exec_modes,
        metavar="",
        nargs=1,
        type=str,
        default=["sequential"],
        help="Defines how SpeeduPy's should load cached data saved on the storage",
    )

    speedupy_arg_parser.add_argument(
        "--mem-arch",
        choices=memory_architectures,
        metavar="",
        nargs=1,
        type=str,
        default=["2-dict-fast"],
        help="Defines how SpeeduPy's should store the data on RAM during the experiment execution",
    )

    speedupy_arg_parser.add_argument(
        "-H",
        "--hash",
        choices=hashes,
        metavar="",
        nargs=1,
        default=["xxhash"],
        help="SpeeduPy's mechanism of hashes: choose one of the following options: "
        + ", ".join(hashes),
    )

    speedupy_arg_parser.add_argument(
        "-s",
        "--storage",
        choices=storage_options,
        metavar="",
        nargs=1,
        default=["sqlite"],
        help="SpeeduPy's mechanism of storage: choose one of the following options: "
        + ", ".join(storage_options),
    )

    speedupy_arg_parser.add_argument(
        "--serializer",
        choices=serializer_options,
        metavar="",
        nargs=1,
        default=["cloudpickle"],
        help="SpeeduPy's serialization mechanism: choose one of the following options: "
        + ", ".join(serializer_options),
    )

    speedupy_arg_parser.add_argument(
        "-mt",
        "--min-exec-time-to-memoize",
        default=[0.01],
        metavar="",
        type=float,
        nargs=1,
        help="defines the minimum execution time a pure function call must have to be memoized by SpeeduPy.",
    )

    speedupy_arg_parser.add_argument(
        "--measure-time",
        action="store_true",
        help="enables time measure of the script execution.",
    )

    speedupy_arg_parser.add_argument(
        "--profile",
        action="store_true",
        help="enables profiling of the script execution.",
    )

    return speedupy_arg_parser


def get_params():
    args = build_parser().parse_args()

    argsp_mem_arch = args.mem_arch
    argsp_retrieval_strategy = args.retrieval_strategy
    argsp_retrieval_exec_mode = args.retrieval_exec_mode
    argsp_hash = args.hash
    argsp_s = args.storage
    argsp_serializer = args.serializer
    argsp_mt = args.min_exec_time_to_memoize
    argsp_measure_time = args.measure_time
    argsp_profile = args.profile

    argsp_exec_mode = args.exec_mode
    argsp_revalidation = args.revalidation
    argsp_max_num_exec_til_revalidation = args.max_num_exec_til_revalidation
    argsp_reduction_factor = args.reduction_factor
    argsp_min_num_exec = args.min_num_exec
    argsp_min_mode_occurrence = args.min_mode_occurrence
    argsp_confidence_level = args.confidence_level
    argsp_max_error_per_function = args.max_error_per_function

    return (
        argsp_mem_arch,
        argsp_retrieval_strategy,
        argsp_retrieval_exec_mode,
        argsp_hash,
        argsp_s,
        argsp_serializer,
        argsp_mt,
        argsp_measure_time,
        argsp_profile,
        argsp_exec_mode,
        argsp_revalidation,
        argsp_max_num_exec_til_revalidation,
        argsp_reduction_factor,
        argsp_min_num_exec,
        argsp_min_mode_occurrence,
        argsp_confidence_level,
        argsp_max_error_per_function,
    )
